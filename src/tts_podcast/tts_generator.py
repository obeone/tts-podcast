"""
Text-to-Speech generator using Gemini's multi-speaker TTS API.

Each :class:`~tts_podcast.llm_summarizer.DialogueChunk` is converted into
raw PCM audio bytes (24 kHz, mono, 16-bit signed little-endian) by calling
the configured Gemini TTS model with a
:class:`~google.genai.types.MultiSpeakerVoiceConfig`.

Two request shapes exist, picked from the model name by
:func:`tts_podcast.tts_models.uses_speech_metadata`:

* Models before Gemini 3.8 get a natural-language audio profile preamble
  prepended to each chunk.  It defines each host's personality, the scene
  context, and director's notes so that Gemini TTS interprets inline
  emotional cues (e.g. "(avec enthousiasme)") generated by the LLM with the
  right character voices.
* Gemini 3.8 TTS and later read the text as a verbatim transcript, so a
  preamble would be spoken aloud.  Each speaker turn is sent as its own part
  with ``speech_metadata`` (speaker plus a short delivery style) instead, and
  the WAV container these models answer with is unwrapped back to raw PCM.

Chunks are processed in parallel using a thread pool (up to 5 concurrent
requests) to reduce total wall-clock time.
"""

from __future__ import annotations

import io
import logging
import wave
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import TYPE_CHECKING, Any

from google import genai
from google.genai import types

from tts_podcast.retry import gemini_retry
from tts_podcast.tts_models import uses_speech_metadata

if TYPE_CHECKING:
    from rich.progress import Progress

    from tts_podcast.llm_summarizer import DialogueChunk
    from tts_podcast.token_tracker import TokenTracker

logger = logging.getLogger(__name__)

# Maximum number of concurrent TTS API requests.
_TTS_MAX_WORKERS = 5

# Default sampling temperature for the TTS model.
# Each chunk is a long, standalone generation (a couple of KB of text) started
# from the same calm preamble (pre-3.8 models) or the same per-speaker style
# strings (3.8+).  At temperature 1.0 the multi-speaker model
# tends to drift toward over-expression as it reads on — an enthusiastic host
# ramps up within a chunk and "runs out of breath", giving an audible
# per-chunk sawtooth.  A lower default keeps prosody steady while staying
# natural.  Override via ``gemini.tts_style.temperature`` in config.
_DEFAULT_TTS_TEMPERATURE = 0.7


def _build_tts_prompt(chunk_text: str, gemini_cfg: dict) -> str:
    """
    Prepend a natural-language audio profile preamble to a dialogue chunk.

    The preamble instructs Gemini TTS to apply consistent speaker personalities,
    keep each host's energy steady across the whole chunk (no build-up or
    crescendo, breathe between sentences), and honour inline emotional cues
    written in parentheses within the dialogue.

    Parameters
    ----------
    chunk_text : str
        The raw dialogue text for this chunk (e.g. "Alex: (avec enthousiasme) ...").
    gemini_cfg : dict
        Resolved Gemini configuration section.  Uses ``speaker1``, ``speaker2``
        (each with ``name``, an optional ``personality`` key and an optional
        ``voice_direction`` key), ``language`` (default ``"French"``), an
        optional ``tts_style.scene`` string, and an optional
        ``tts_style.pace`` string that provides a natural-language
        description of the desired speaking pace (e.g. ``"slow and deliberate"``).
        When absent, defaults to ``"natural"``.

    Returns
    -------
    str
        The preamble followed by the dialogue text, ready for the TTS API.

    Notes
    -----
    ``personality`` is read **verbatim** and is never mutated.  The
    ``voice_direction`` key is TTS-only: it describes register, tempo,
    articulation and breathing, and must never reach the dialogue prompt
    built by :func:`tts_podcast.llm_summarizer._build_prompt`.  Conversely the
    dialogue-only ``style_overlay`` key is never read here.  When a speaker
    declares no ``voice_direction`` the rendered preamble is byte-identical to
    the pre-``voice_direction`` output, so legacy configs sound unchanged.
    """
    s1 = gemini_cfg["speaker1"]
    s2 = gemini_cfg["speaker2"]
    tts_style = gemini_cfg.get("tts_style", {})
    scene = tts_style.get("scene", "")
    pace = tts_style.get("pace", "natural")
    language = gemini_cfg.get("language", "French")

    s1_personality = s1.get("personality", "enthusiastic and curious")
    s2_personality = s2.get("personality", "analytical and thoughtful")

    def _direction_line(speaker: dict) -> str:
        """
        Render one speaker's voice direction line, or an empty string.

        Parameters
        ----------
        speaker : dict
            A ``speakerN`` config block.

        Returns
        -------
        str
            ``"Voice direction for <name>: <direction>\\n"`` when the speaker
            declares a non-blank ``voice_direction``, otherwise ``""`` so the
            preamble stays byte-identical for legacy configs.
        """
        # str() guards the library entry point: the CLI validates the type up
        # front (duos.validate_speaker), but a caller building the config in
        # Python must not be able to turn a stray non-string into an
        # AttributeError inside the TTS thread pool.
        raw = speaker.get("voice_direction") or ""
        direction = raw.strip() if isinstance(raw, str) else str(raw).strip()
        if not direction:
            return ""
        # Attribute the note to the host by name: an unattributed note lets the
        # model average both deliveries, which is exactly the sameness we fix.
        return f"Voice direction for {speaker['name']}: {direction}\n"

    preamble = (
        f"Audio profile: Two hosts of a {language} tech podcast, speaking in {language}.\n"
        f"{s1['name']} is {s1_personality}.\n"
        f"{_direction_line(s1)}"
        f"{s2['name']} is {s2_personality}.\n"
        f"{_direction_line(s2)}"
    )
    if scene:
        preamble += f"Scene: {scene}\n"
    preamble += (
        f"Director's notes: Conversational pace — {pace}; speak clearly, "
        "allow a natural beat between sentences so the listener can absorb each idea. "
        "Keep each host's energy level steady from the first line to the last: do not "
        "build up, speed up, or crescendo as the passage goes on. Breathe — leave a "
        "clear pause at every sentence boundary and never run turns together. React "
        "genuinely and stay in character; an enthusiastic host stays warmly enthusiastic, "
        "not increasingly frantic. "
        "Honour any emotional cues written in parentheses in the dialogue.\n\n"
    )
    return preamble + chunk_text


def _split_turns(chunk_text: str, speaker_names: tuple[str, str]) -> list[tuple[str, str]]:
    """
    Split a dialogue chunk into ``(speaker, text)`` turns.

    Parameters
    ----------
    chunk_text : str
        Chunk text made of ``Name: line`` turns, as produced by
        :func:`tts_podcast.llm_summarizer._split_dialogue_into_chunks`.
    speaker_names : tuple[str, str]
        The two configured host names, first speaker first.

    Returns
    -------
    list[tuple[str, str]]
        Ordered turns with the ``Name:`` prefix removed.  Turns left with no
        text are dropped.

    Notes
    -----
    A line that does not open with a known speaker prefix continues the turn
    before it.  Such a line at the very start of a chunk has no turn to join,
    so it is given to the first speaker rather than discarded: losing a
    sentence is worse than voicing it with the wrong host.
    """
    turns: list[tuple[str, list[str]]] = []
    for line in chunk_text.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        for name in speaker_names:
            prefix = f"{name}:"
            if stripped.startswith(prefix):
                turns.append((name, [stripped[len(prefix):].strip()]))
                break
        else:
            if not turns:
                logger.warning(
                    "Dialogue line without a speaker prefix, voiced as %s: %r",
                    speaker_names[0],
                    stripped[:80],
                )
                turns.append((speaker_names[0], []))
            turns[-1][1].append(stripped)

    joined = ((name, " ".join(part for part in parts if part)) for name, parts in turns)
    return [(name, text) for name, text in joined if text]


def _speaker_style(speaker: dict, gemini_cfg: dict) -> str | None:
    """
    Build the turn-level ``style`` string for one host.

    Parameters
    ----------
    speaker : dict
        A ``speakerN`` config block.
    gemini_cfg : dict
        Resolved Gemini configuration section (reads ``tts_style.pace``).

    Returns
    -------
    str or None
        The speaker's ``voice_direction`` followed by the configured pace, or
        ``None`` when neither is set, in which case the turn is sent with no
        style at all.

    Notes
    -----
    Only sustained delivery traits belong here.  ``personality`` and
    ``tts_style.scene`` are deliberately left out: on the speech-metadata
    schema, persona and scene prose is what makes a voice drift, and the
    configured voice already carries the speaker's identity.  The same string
    is reused for every turn of a host, which is what keeps the delivery
    steady from one turn, and one chunk, to the next.
    """
    raw = speaker.get("voice_direction") or ""
    direction = raw.strip() if isinstance(raw, str) else str(raw).strip()
    pace = str(gemini_cfg.get("tts_style", {}).get("pace") or "").strip()
    pieces = [direction, f"Pace: {pace}" if pace else ""]
    style = " ".join(piece for piece in pieces if piece)
    return style or None


def _build_tts_parts(chunk_text: str, gemini_cfg: dict) -> list[types.Part]:
    """
    Convert a dialogue chunk into structured turns for Gemini 3.8+ TTS.

    These models read the text as a verbatim transcript, so the legacy
    preamble and the ``Name:`` prefixes would be spoken aloud.  Each turn
    becomes one part instead: the bare transcript as ``text``, with the
    speaker and a short delivery style in ``speech_metadata``.

    Parameters
    ----------
    chunk_text : str
        The raw dialogue text for this chunk (``Name: line`` turns).
    gemini_cfg : dict
        Resolved Gemini configuration section.  Uses ``speaker1`` and
        ``speaker2`` (``name``, optional ``voice_direction``) and the optional
        ``tts_style.pace``.

    Returns
    -------
    list[types.Part]
        One part per speaker turn, in dialogue order.
    """
    speakers = (gemini_cfg["speaker1"], gemini_cfg["speaker2"])
    styles = {s["name"]: _speaker_style(s, gemini_cfg) for s in speakers}
    names = (speakers[0]["name"], speakers[1]["name"])
    return [
        types.Part(
            text=text,
            speech_metadata=types.SpeechMetadata(speaker=name, style=styles[name]),
        )
        for name, text in _split_turns(chunk_text, names)
    ]


def _to_pcm(data: bytes, chunk_index: int) -> bytes:
    """
    Return headerless PCM from a TTS audio payload.

    Earlier models answer with raw PCM; Gemini 3.8 TTS answers with a complete
    WAV file on unary requests.  The rest of the pipeline concatenates raw PCM
    chunks, so a WAV container is unwrapped here.

    Parameters
    ----------
    data : bytes
        Audio bytes from the response's inline data.
    chunk_index : int
        Index of the chunk, used in error messages.

    Returns
    -------
    bytes
        Raw 24 kHz / mono / 16-bit signed little-endian audio.

    Raises
    ------
    RuntimeError
        If the payload is a WAV file in any other sample format: the exporter
        assumes that exact format, and stitching anything else in would play
        back at the wrong speed or as noise.
    """
    # Sniff the container instead of trusting the declared MIME type: it is the
    # bytes that get concatenated, whatever the response says they are.
    if data[:4] != b"RIFF" or data[8:12] != b"WAVE":
        return data
    with wave.open(io.BytesIO(data), "rb") as wav:
        layout = (wav.getframerate(), wav.getnchannels(), wav.getsampwidth())
        if layout != (24000, 1, 2):
            raise RuntimeError(
                f"Unexpected TTS audio format for chunk {chunk_index}: "
                f"{layout[0]} Hz, {layout[1]} channel(s), {layout[2] * 8}-bit "
                "(expected 24000 Hz, mono, 16-bit)"
            )
        return wav.readframes(wav.getnframes())


def _generate_chunk_audio(
    chunk: DialogueChunk,
    client: genai.Client,
    gemini_cfg: dict,
    voice_config: types.MultiSpeakerVoiceConfig,
    temperature: float,
) -> tuple[bytes, Any]:
    """
    Generate PCM audio for a single dialogue chunk.

    Builds the request contents for the model's schema (a preamble string for
    models before Gemini 3.8, one ``speech_metadata`` part per turn from 3.8
    on), calls the Gemini TTS API with retry, and returns the raw PCM bytes
    (a WAV payload is unwrapped by :func:`_to_pcm`) together with the
    response usage metadata for token accounting.

    Parameters
    ----------
    chunk : DialogueChunk
        The dialogue chunk to synthesise.
    client : genai.Client
        Authenticated Gemini client.
    gemini_cfg : dict
        Resolved Gemini configuration (needs ``tts_model`` key).
    voice_config : types.MultiSpeakerVoiceConfig
        Pre-built multi-speaker voice configuration.
    temperature : float
        Sampling temperature for the TTS model.

    Returns
    -------
    tuple[bytes, Any]
        ``(pcm_bytes, usage_metadata)`` where ``pcm_bytes`` is raw 24 kHz /
        mono / 16-bit LE audio and ``usage_metadata`` is the
        ``response.usage_metadata`` object (may be ``None``).

    Raises
    ------
    RuntimeError
        If the TTS API returns an unexpected response structure, if a chunk
        sent to a Gemini 3.8+ model holds no speaker turn, or if a WAV payload
        is not 24 kHz / mono / 16-bit.
    """
    contents: str | list[types.Part]
    if uses_speech_metadata(gemini_cfg["tts_model"]):
        contents = _build_tts_parts(chunk.text, gemini_cfg)
        if not contents:
            raise RuntimeError(f"Chunk {chunk.index} contains no speaker turn to synthesise")
        logger.debug(
            "Generating TTS for chunk %d (%d bytes text, %d structured turns)",
            chunk.index,
            len(chunk.text.encode("utf-8")),
            len(contents),
        )
    else:
        contents = _build_tts_prompt(chunk.text, gemini_cfg)
        logger.debug(
            "Generating TTS for chunk %d (%d bytes text, %d bytes with preamble)",
            chunk.index,
            len(chunk.text.encode("utf-8")),
            len(contents.encode("utf-8")),
        )

    @gemini_retry
    def _call() -> genai.types.GenerateContentResponse:
        return client.models.generate_content(
            model=gemini_cfg["tts_model"],
            contents=contents,
            config=types.GenerateContentConfig(
                response_modalities=["AUDIO"],
                temperature=temperature,
                speech_config=types.SpeechConfig(
                    multi_speaker_voice_config=voice_config,
                ),
            ),
        )

    response = _call()

    try:
        audio: bytes = response.candidates[0].content.parts[0].inline_data.data
    except (IndexError, AttributeError, TypeError) as exc:
        raise RuntimeError(
            f"Unexpected TTS response structure for chunk {chunk.index}: {exc}"
        ) from exc
    pcm_bytes = _to_pcm(audio, chunk.index)

    logger.info(
        "Chunk %d: received %d bytes of PCM audio",
        chunk.index,
        len(pcm_bytes),
    )
    return pcm_bytes, response.usage_metadata


def generate_audio_chunks(
    chunks: list[DialogueChunk],
    gemini_cfg: dict,
    token_tracker: TokenTracker | None = None,
    progress: Progress | None = None,
    task_id: Any = None,
) -> list[bytes]:
    """
    Convert a list of dialogue chunks into raw PCM audio bytes using Gemini TTS.

    Each chunk is sent as a separate TTS request so that the request stays
    within the model's input limit.  Requests are issued in parallel (up to
    :data:`_TTS_MAX_WORKERS` concurrent workers) and results are returned in
    the same order as the input.  For models before Gemini 3.8 a
    natural-language audio profile preamble is prepended to each chunk to give
    the TTS model personality and emotional context; Gemini 3.8+ models get
    one ``speech_metadata`` part per speaker turn instead (see
    :func:`_build_tts_parts`).

    Parameters
    ----------
    chunks : list[DialogueChunk]
        Ordered dialogue chunks produced by
        :func:`~tts_podcast.llm_summarizer.generate_dialogue`.
    gemini_cfg : dict
        Resolved Gemini configuration with keys:
        ``api_key``, ``tts_model``, ``speaker1`` ({``name``, ``voice``,
        ``personality``, optional ``voice_direction``}), ``speaker2`` (same
        shape), ``language`` (default ``"French"``), and optional
        ``tts_style`` ({``scene``, ``pace``, ``temperature``}).
    token_tracker : TokenTracker or None, optional
        When provided, records token usage for every TTS API call.
    progress : rich.progress.Progress or None, optional
        A rich :class:`~rich.progress.Progress` instance.  When provided,
        ``task_id`` must also be supplied and will be advanced once per
        completed chunk.
    task_id : Any, optional
        Task identifier returned by ``progress.add_task()``.

    Returns
    -------
    list[bytes]
        One PCM bytes object per input chunk, in the same order.
        Each bytes object is raw 24 kHz / mono / 16-bit signed little-endian audio.

    Raises
    ------
    RuntimeError
        If the Gemini API returns an unexpected response structure or audio
        format for any chunk, or a Gemini 3.8+ chunk holds no speaker turn.

    Examples
    --------
    >>> audio_chunks = generate_audio_chunks(dialogue_chunks, gemini_cfg)
    >>> len(audio_chunks) == len(dialogue_chunks)
    True
    """
    client = genai.Client(api_key=gemini_cfg["api_key"])

    speaker1_cfg = gemini_cfg["speaker1"]
    speaker2_cfg = gemini_cfg["speaker2"]
    temperature = gemini_cfg.get("tts_style", {}).get(
        "temperature", _DEFAULT_TTS_TEMPERATURE
    )

    voice_config = types.MultiSpeakerVoiceConfig(
        speaker_voice_configs=[
            types.SpeakerVoiceConfig(
                speaker=speaker1_cfg["name"],
                voice_config=types.VoiceConfig(
                    prebuilt_voice_config=types.PrebuiltVoiceConfig(
                        voice_name=speaker1_cfg["voice"],
                    )
                ),
            ),
            types.SpeakerVoiceConfig(
                speaker=speaker2_cfg["name"],
                voice_config=types.VoiceConfig(
                    prebuilt_voice_config=types.PrebuiltVoiceConfig(
                        voice_name=speaker2_cfg["voice"],
                    )
                ),
            ),
        ]
    )

    if not chunks:
        return []

    max_workers = min(_TTS_MAX_WORKERS, len(chunks))
    logger.info(
        "Generating TTS for %d chunk(s) with up to %d worker(s)…",
        len(chunks),
        max_workers,
    )

    # Submit all chunks to the thread pool.  Use as_completed so the
    # progress bar advances as soon as *any* chunk finishes, then
    # reassemble results in the original order for audio sequencing.
    results: dict[int, bytes] = {}
    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        future_to_index = {
            executor.submit(
                _generate_chunk_audio,
                chunk,
                client,
                gemini_cfg,
                voice_config,
                temperature,
            ): i
            for i, chunk in enumerate(chunks)
        }
        for future in as_completed(future_to_index):
            idx = future_to_index[future]
            pcm_bytes, usage_metadata = future.result()
            results[idx] = pcm_bytes
            if token_tracker is not None:
                token_tracker.record_usage(gemini_cfg["tts_model"], usage_metadata)
            if progress is not None and task_id is not None:
                progress.advance(task_id)
                if token_tracker is not None:
                    progress.update(
                        task_id,
                        description=f"[cyan]TTS synthesis[/cyan] — {token_tracker.live_line()}",
                    )

    return [results[i] for i in range(len(chunks))]
